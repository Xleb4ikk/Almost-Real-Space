        static PixelFont()
        {
            glyphs = Build();
        }

        public static Glyph Get(char c)
        {
            Glyph g;
            if (glyphs.TryGetValue(c, out g))
            {
                return g;
            }

            return unknown;
        }

        private static Dictionary<char, Glyph> Build()
        {
            var map = new Dictionary<char, Glyph>();
            for (int i = 0; i < Table.Length; i++)
            {
                string entry = Table[i];
                char key = entry[0];
                string[] rows = entry.Substring(2).Split('/');
                int width = 0;
                for (int r = 0; r < rows.Length; r++)
                {
                    width = System.Math.Max(width, rows[r].Length);
                }

                ulong bits = 0UL;
                for (int r = 0; r < rows.Length && r < CellHeight; r++)
                {
                    for (int x = 0; x < rows[r].Length; x++)
                    {
                        if (rows[r][x] == '#')
                        {
                            bits |= 1UL << ((r * 8) + x);
                        }
                    }
                }

                map[key] = new Glyph { Bits = bits, Width = width };
            }

            Glyph q;
            map.TryGetValue('?', out q);
            unknown = q;

            // Строчные → заглавные; Ё остаётся отдельным глифом.
            for (char c = 'a'; c <= 'z'; c++)
            {
                map[c] = map[char.ToUpperInvariant(c)];
            }

            for (char c = '\u0430'; c <= '\u044F'; c++)
            {
                map[c] = map[(char)(c - 0x20)];
            }

            map['\u0451'] = map['\u0401'];
            return map;
        }
